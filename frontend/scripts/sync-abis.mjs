// Copies compiled ABIs from ../contracts/out into lib/abis/*.ts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "..", "contracts", "out");
const read = (name) => JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8")).abi;
const write = (file, constName, abi, from) => {
  const src = `// Generated by scripts/sync-abis.mjs from ${from}. Do not edit.\nexport const ${constName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(join(root, "lib", "abis", `${file}.ts`), src);
  console.log(`wrote lib/abis/${file}.ts (${abi.length} entries)`);
};

const targets = [
  // v1 (BNB quote)
  ["VLEIRegistry", "registryAbi"],
  ["VLEILauncherFactory", "factoryAbi"],
  ["VLEIMintLauncher", "launcherAbi"],
  // v2 (ERC20 quote, e.g. USDT, or BNB) + the gated vault
  ["VLEIMintVaultLauncherV2", "vaultLauncherV2Abi"],
  ["VLEIVaultLauncherFactoryV2", "vaultLauncherFactoryV2Abi"],
  ["VLEILauncherFactoryV2", "launcherFactoryV2Abi"],
  ["VLEIDividendVaultV2", "vaultV2Abi"],
];
for (const [name, constName] of targets) write(name, constName, read(name), `contracts/out/${name}.sol/${name}.json`);

// Minimal ERC20: IERC20Metadata functions + the testnet mock quote token's public mint(address,uint256).
const erc20 = [
  ...read("IERC20Metadata").filter((i) => i.type === "function"),
  ...read("MockQuoteToken").filter((i) => i.type === "function" && i.name === "mint"),
];
write("ERC20", "erc20Abi", erc20, "IERC20Metadata + MockQuoteToken.mint");
